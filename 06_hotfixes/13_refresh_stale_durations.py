#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.10"
# dependencies = ["click", "loguru", "jiwer>=3.0", "requests>=2.31", "tqdm>=4.66",
#                 "soundfile>=0.12", "numpy"]
