"""Refresh the state rows' `duration` / `voice` from the manifests, and rescore the one
metric that depends on duration: `cer_tail`.

Run AFTER the manifests have been rebuilt from the audio (``REFRESH_MANIFESTS=1``) and
BEFORE ``99_hf_release/03_sync_hotfix_results.py --apply``, which copies `cer_tail` into
the release columns:

    uv run 13_refresh_stale_durations.py             # dry run, reports what would move
    uv run 13_refresh_stale_durations.py --apply

The bug it repairs. Every sweep updates the READINGS of a row (`transcriptions`) but
none of them rewrites the row's own `duration`: only a redraw does
(``01_recursive_improvement.py``, which writes the new take's length). So a clip whose
audio was regenerated by the v2 nine-voice pass, and then re-read by the whisper and
parakeet sweeps, ends up with current transcripts beside a v1-era duration. Measured on
2026-10-26 over `improved/` + `improved_parrot/`: 208,235 of 604,337 rows disagree with
the manifest, 208,153 of those also have no `voice`, and the disagreement is not a
rounding artefact (`015709_0000_gynecologie_00047_t1_c0` says 34.0 s against a file that
is 86.96 s, and `000000_0000_parrot_50_c0` says 63.28 s against 12.00 s).

The readings themselves are NOT stale, which is why this is a field repair and not a
rescore: on the mismatching rows the stored transcript runs at 14.69 characters per
second of the MANIFEST duration (14.64 on the rows that agree) against 16.67 per second
of the stored one, and their turbo CER distribution matches the fresh rows (median
0.0109 vs 0.0118). The transcripts describe the audio on disk; only the number beside
them is old.

What a stale duration actually costs: `_stt.tail_cer` returns None at or under
`TAIL_SECONDS` (30 s), so the tail gate, the one that asks "did this clip END the way it
was supposed to", silently skipped 5,250 clips that really are longer than 30 s, and
scored a tail on 229 that are not. That is the truncation / derail-at-the-end blind spot,
and it needs no GPU to close: `tail_cer` is a function of the stored reference, the
stored transcript and the duration. `stt_rtf` is refreshed for the same reason (it is
seconds / duration).

Nothing else is touched. In particular `cer`, `cer_window`, `bad_run_chars` and
`repeat_excess` are length-independent by construction, so a wrong duration never moved
them, and rewriting them here would make this script a second owner of metrics that
already have one.

`voice` is filled but never corrected, which is the opposite of how `duration` is treated
here and is deliberate: see `refresh_row`. The manifest is the truth about length (it was
probed from the file) and the state is the truth about who read the clip (a voice swap is
recorded there and nowhere else).

Except when the manifest is OLDER than the audio, which is the driver's own step order:
the manifests are rebuilt first, the redraw rounds then overwrite clips (and
``01_recursive_improvement.py`` writes the new take's length into the state row), and
this script runs last. Trusting the manifest there handed every clip redrawn in the run
its previous take's length back: 108 PARHAF clips on 2026-11-01, e.g.
``002522_0000_cancero_adulte_00042_t0_c0``, file 31.04 s, state set to 31.04 by the
redraw, then reset to the manifest's 45.28 (the take in ``.flac.bak2``). So a
disagreement is settled by the file itself (``nemo_manifest.probe_durations``, header
only, a few hundred clips per run), and the manifest's number is used only when the file
cannot be read. ``--probe-files`` also probes every ``improved`` row whose state and
manifest AGREE, to repair rows this bug already reset (both sides then carry the old
take's length, so nothing else can see them).

This file was written with Claude Code.
"""
from __future__ import annotations

import importlib.util
import json
import os
import sys
from collections import Counter
from pathlib import Path

import click
from loguru import logger

_HERE = Path(__file__).resolve().parent
ROOT = _HERE.parent
sys.path.insert(0, str(ROOT / "utils"))

from nemo_manifest import clip_key, probe_durations  # noqa: E402

#: Where the state files live, relative to this directory.
DEFAULT_STATES = ("improved/full.stt.jsonl", "improved_parrot/full.stt.jsonl")
#: The manifest that owns the truth about a clip's length: `01_build_nemo_manifest.py`
#: statts every file to build it, so it is the audio's own answer, one join away.
DEFAULT_MANIFEST = ROOT / "99_hf_release" / "data" / "NeMO_files" / "full.jsonl"
#: Below this the two durations are the same number written twice.
TOL_S = 0.05


def _load_stt():
    """Stage 06's scorer, via the one module that already knows where it lives.

    `12_merge_judge_sidecars.py` owns that path (and the reason for loading the scorer
    rather than reimplementing it), so this goes through its `_load_stt` instead of
    spelling out a fifth copy of the same `spec_from_file_location` dance.
    """
    path = _HERE / "12_merge_judge_sidecars.py"
    spec = importlib.util.spec_from_file_location("merge_judge_sidecars", path)
    if spec is None or spec.loader is None:
        raise ImportError(f"cannot load {path}")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod._load_stt()


def load_truth(manifest: Path) -> dict[str, tuple[float | None, str | None]]:
    """``{clip_key: (duration, voice)}`` from a NeMo manifest, streamed.

    Keyed on `clip_key` (``dictionary/012095_0006_x.flac``) rather than the bare stem
    because that is the corpus-wide identity the rest of the repo joins on, and both
    sides spell the path the same way (``../<source>/<file>``).
    """
    truth: dict[str, tuple[float | None, str | None]] = {}
    with manifest.open(encoding="utf-8") as handle:
        for line in handle:
            if not line.strip():
                continue
            row = json.loads(line)
            truth[clip_key(row["audio_filepath"])] = (row.get("duration"), row.get("voice"))
    return truth


def _disagrees(old, new) -> bool:
    return new is not None and (old is None or abs(float(old) - float(new)) > TOL_S)


def probe_candidates(path: Path, truth: dict, manifest: Path, *,
                     probe_improved: bool) -> dict[str, float]:
    """``{clip_key: duration read from the file}`` for the rows of state ``path`` whose
    length is in doubt: the manifest disagrees with the state (either side may be the
    stale one, see the module docstring), or, with ``probe_improved``, the row was
    redrawn (``improvement.status == "improved"``).

    The file read is the one the MANIFEST points at, never the state row's own path: the
    PARROT state spells its paths relative to ``NeMO_files/PARROT`` (``../../PARROT/x``),
    and joined onto the manifest's directory that walks through the ``data`` symlink onto
    the v1 tree's file of the same name, a different take (2026-11-02, Claude Code: 89
    PARROT rows written with v1 lengths)."""
    keys: set[str] = set()
    with path.open(encoding="utf-8") as handle:
        for line in handle:
            if not line.strip():
                continue
            row = json.loads(line)
            key = clip_key(row.get("audio_filepath", ""))
            if key not in truth:
                continue
            improved = ((row.get("improvement") or {}).get("status") == "improved")
            if _disagrees(row.get("duration"), truth[key][0]) or (probe_improved and improved):
                keys.add(key)
    if not keys:
        return {}
    paths: dict[str, Path] = {}
    with manifest.open(encoding="utf-8") as handle:
        for line in handle:
            if line.strip():
                rel = json.loads(line)["audio_filepath"]
                if clip_key(rel) in keys:
                    paths[clip_key(rel)] = manifest.parent / rel
    by_name = probe_durations(list(paths.values()), progress=len(paths) > 1000)
    return {key: by_name[p.name] for key, p in paths.items() if p.name in by_name}


def refresh_row(row: dict, truth: dict, stt, counts: Counter,
                probed: dict[str, float] | None = None) -> bool:
    """Repair one row in place. True when anything changed. ``probed`` holds the file's
    own duration for the rows `probe_candidates` picked, which beats the manifest's.

    The reference for `cer_tail` is `text`, the LABEL, the same choice
    `08_validate_manifests.py` recomputes against: `asr_training_source` carries the TTS
    respellings, and scoring against it charges a respelling as a recognition error.
    """
    key = clip_key(row.get("audio_filepath", ""))
    if key not in truth:
        counts["clip_not_in_manifest"] += 1
        return False
    duration, voice = truth[key]
    from_file = (probed or {}).get(key)
    if from_file is not None:
        if _disagrees(duration, from_file):
            counts["manifest_stale_file_wins"] += 1
        duration = round(from_file, 4)
    old = row.get("duration")
    changed = False
    if _disagrees(old, duration):
        row["duration"] = duration
        counts["duration_refreshed"] += 1
        changed = True
    # FILL ONLY, never correct. The two sides are not symmetric here the way they are for
    # duration: a clip no draw of its own voice could fix is redrawn by another voice
    # (`01_recursive_improvement.py --voice-swap`), the state row is the only place that
    # records it, and `01_build_nemo_manifest.py` RE-DERIVES the column from the
    # assignment hash, which cannot know about the swap. So on a row that already has a
    # voice the manifest's value is the derived guess and the state's is the measurement;
    # overwriting would hand a swapped clip back the voice that never read it, and the
    # sync would then copy that into the release. Disagreements are counted, not resolved.
    if voice and not row.get("voice"):
        row["voice"] = voice
        counts["voice_filled"] += 1
        changed = True
    elif voice and row.get("voice") != voice:
        counts["voice_disagrees_state_kept"] += 1
    if not changed:
        return False

    reference = row.get("text")
    for judge, reading in (row.get("transcriptions") or {}).items():
        if not isinstance(reading, dict):
            continue
        transcript = reading.get("text")
        if reference and transcript:
            before = reading.get("cer_tail")
            after = stt.tail_cer(reference, transcript, row["duration"])
            after = None if after is None else round(after, 4)
            if before != after:
                reading["cer_tail"] = after
                if before is None:
                    counts["tail_added"] += 1
                    if after is not None and after >= stt.DEFAULT_TAIL_CER_GATE:
                        counts["tail_added_OVER_GATE"] += 1
                        counts[f"tail_added_over_gate::{judge}"] += 1
                elif after is None:
                    counts["tail_removed"] += 1
                else:
                    counts["tail_rescored"] += 1
        seconds, dur = reading.get("stt_seconds"), row["duration"]
        if seconds is not None and isinstance(dur, (int, float)) and dur > 0:
            rtf = round(float(seconds) / float(dur), 5)
            if reading.get("stt_rtf") != rtf:
                reading["stt_rtf"] = rtf
                counts["rtf_refreshed"] += 1
    return True


def refresh_file(path: Path, truth: dict, stt, *, apply: bool,
                 probed: dict[str, float] | None = None) -> Counter:
    """Stream one state file through `refresh_row`.

    Streamed rather than `read_jsonl`-ed because `improved/full.stt.jsonl` is ~800 MB of
    JSON: materialising it as a list of dicts costs several GB of RAM for no gain, since
    every row is touched exactly once and in order.
    """
    counts = Counter()
    tmp = path.with_suffix(path.suffix + ".refresh.tmp")
    out = tmp.open("w", encoding="utf-8") if apply else None
    try:
        with path.open(encoding="utf-8") as handle:
            for line in handle:
                if not line.strip():
                    continue
                row = json.loads(line)
                counts["rows"] += 1
                if refresh_row(row, truth, stt, counts, probed):
                    counts["rows_changed"] += 1
                if out is not None:
                    out.write(json.dumps(row, ensure_ascii=False) + "\n")
    finally:
        if out is not None:
            out.close()
    if apply:
        os.replace(tmp, path)
    elif tmp.exists():
        tmp.unlink()
    return counts


@click.command()
@click.option("--state", "states", multiple=True, type=click.Path(path_type=Path),
              help=f"State file to repair. Default: {' '.join(DEFAULT_STATES)}")
@click.option("--manifest", default=str(DEFAULT_MANIFEST), show_default=False,
              type=click.Path(path_type=Path), help="The manifest that owns durations.")
@click.option("--apply", is_flag=True, help="Write. Without it this is a dry run.")
@click.option("--probe-files", is_flag=True,
              help="Also read the audio of every `improved` row whose state and manifest "
                   "agree (repairs rows an older run reset to the previous take's length).")
def main(states: tuple[Path, ...], manifest: Path, apply: bool, probe_files: bool = False) -> None:
    """Make the state rows' durations match the audio, and rescore the tail gate."""
    manifest = Path(manifest)
    if not manifest.exists():
        raise SystemExit(f"no manifest at {manifest} (is the `data` symlink mounted?)")
    targets = list(states) or [_HERE / name for name in DEFAULT_STATES]
    targets = [p for p in targets if p.exists()]
    if not targets:
        raise SystemExit("no state file found")

    truth = load_truth(manifest)
    logger.info(f"{manifest.name}: {len(truth)} stems own a duration")
    stt = _load_stt()
    total = Counter()
    for path in targets:
        probed = probe_candidates(path, truth, manifest, probe_improved=probe_files)
        counts = refresh_file(path, truth, stt, apply=apply, probed=probed)
        counts["files_probed"] = len(probed)
        # A `--state` given by hand can sit anywhere, so shorten only when it really is
        # under this directory rather than letting relative_to raise on everything else.
        resolved = path.resolve()
        label = resolved.relative_to(_HERE) if resolved.is_relative_to(_HERE) else path
        logger.info(f"{label}: {dict(counts)}")
        total.update(counts)
    logger.info(f"total: {dict(total)}")
    if total["tail_added_OVER_GATE"]:
        logger.warning(
            f"{total['tail_added_OVER_GATE']} readings gained a tail score at or over the "
            f"{stt.DEFAULT_TAIL_CER_GATE} gate, i.e. clips whose ENDING was never checked "
            "and is bad. Re-run 03_collect_suspicious.py to fold them into the repair round.")
    if not apply:
        logger.warning("dry run, nothing written (pass --apply)")


if __name__ == "__main__":
    main()
